import 'dart:io' show Platform;

import 'package:flutter/foundation.dart' show kIsWeb;

/// Чем платформа отличается от остальных.
///
/// В браузере `Platform` спрашивать нельзя вовсе: вместо ответа он бросает
/// исключение, и приложение падает на первом же обращении. Поэтому проверка
/// всегда начинается с [kIsWeb] — константы, которую компилятор вычисляет
/// заранее и вырезает мёртвую ветку целиком.

/// Android ли это. В браузере — нет.
bool get isAndroid => !kIsWeb && Platform.isAndroid;

/// Есть ли у платформы файлы: снимок обложкой, вложения, выгрузка в файл.
///
/// В браузере файловой системы нет, а песочница OPFS для этого не годится:
/// человек ждёт, что приложенный документ откроется его же программой.
bool get hasFiles => !kIsWeb;

/// Умеет ли платформа будильники и виджеты рабочего стола.
bool get hasAlarms => isAndroid;
