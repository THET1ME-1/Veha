/// Часовой пояс устройства одной точкой на всё приложение.
///
/// Событие помнит свой пояс: занятие в 16:00 обязано остаться в 16:00 после
/// перевода часов и после переезда. Пояс читается системным вызовом, а тот
/// асинхронный — держать его приходится снаружи, иначе каждый конструктор
/// события становится `Future`.
///
/// До первого чтения стоит UTC, а не Кишинёв: зашитый чужой пояс — это тихая
/// ошибка на чужом устройстве, а UTC хотя бы честно нейтрален.
class AppTimezone {
  AppTimezone._();

  static String _current = 'UTC';

  static String get current => _current;

  static void set(String value) {
    if (value.trim().isEmpty) return;
    _current = value;
  }
}
